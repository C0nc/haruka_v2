def tile_ids(adata, tile: int = 8, row_key="array_row", col_key="array_col",
             library_key="slice_id") -> np.ndarray:
    """Contiguous ``tile x tile`` blocks, unique across slices.

    These tiles define BOTH the permutation null and the block bootstrap. A naive
    per-cell bootstrap is far too tight under spatial autocorrelation and will
    manufacture significance.
    """
    rr = np.asarray(adata.obs[row_key], dtype=np.int64)
    cc = np.asarray(adata.obs[col_key], dtype=np.int64)
    sl = pd.factorize(np.asarray(adata.obs[library_key]).astype(str))[0].astype(np.int64)
    nc = int(cc.max() // tile) + 1
    return sl * 1_000_000 + (rr // tile) * nc + (cc // tile)


def tile_permute_index(tiles: np.ndarray, rng) -> np.ndarray:
    """Row index realising a whole-tile permutation. ``values[idx]`` is the draw.

    Returning the INDEX rather than the permuted values lets a caller that has
    already built an O(n^2) kernel reuse it as ``K[np.ix_(idx, idx)]`` instead of
    recomputing the kernel per draw -- exactly equivalent, and the difference
    between a fast permutation null and an unusable one.
    """
    tiles = np.asarray(tiles)
    uniq, inv = np.unique(tiles, return_inverse=True)
    order = np.argsort(inv, kind="stable")
    starts = np.searchsorted(inv[order], np.arange(uniq.size))
    ends = np.searchsorted(inv[order], np.arange(uniq.size), side="right")
    members = [order[a:b] for a, b in zip(starts, ends)]
    perm = rng.permutation(uniq.size)
    idx = np.arange(tiles.shape[0], dtype=np.int64)
    for a, b in enumerate(perm):
        dst, src = members[a], members[b]
        if dst.size == 0 or src.size == 0:
            continue
        take = np.floor(np.linspace(0.0, src.size - 1e-9, dst.size)).astype(np.int64)
        idx[dst] = src[take]
    return idx


def tile_permute(values: np.ndarray, tiles: np.ndarray, rng) -> np.ndarray:
    """Permute WHOLE tiles of ``values``, preserving within-tile autocorrelation.

    Tiles are resampled onto one another by rank position so that unequal tile
    occupancy (holes, ragged edges) does not force a fallback to cell-wise
    shuffling, which would destroy exactly the structure this null exists to keep.
    """
    values = np.asarray(values)
    return values[tile_permute_index(tiles, rng)]


def blocked_cv_folds(
    adata,
    xi: float,
    n_folds: int = 5,
    n_tiles: int = 5,
    R: int | None = None,
    spatial_key: str = "spatial",
    library_key: str = "slice_id",
    return_meta: bool = False,
):
    """Spatially blocked CV with a truth-specific buffer. NON-NEGOTIABLE.

    Each slice is cut into an ``n_tiles x n_tiles`` grid of contiguous tiles, and
    tiles are assigned to folds ROUND-ROBIN so that each fold is several spatially
    separated tiles rather than one giant block -- less extrapolation, same
    independence.

    Every cell within ``buffer = min(3*xi, R/16)`` of any held-out cell is dropped
    from the TRAINING fold. ``xi`` is the correlation range of the truth being
    predicted (``xi_v`` for the niche, ``xi_u`` for the intrinsic factor, ``r0``
    for the salient factor, ``xi_c`` for the decoy), so the buffer is
    truth-specific by construction.

    Note where the statistical care lands: at ``R=128`` the ``R/16`` cap is 8, so
    the headline niche column (``xi_v <= 2`` -> buffer 6) is FULLY buffered, while
    the intrinsic column at ``xi_u=8`` is not (ratio 0.33) and the salient column
    is not (ratio ~0.12). That is the correct priority, and the salient factor is
    scored by within-disease AUROC anyway, not by a cross-slice R^2.

    Returns ``folds`` (list of ``(train_idx, test_idx)``), or ``(folds, meta)``
    when ``return_meta``. ``meta['under_buffered']`` True means the resulting R^2
    is an UPPER BOUND: inflating a diagonal entry flatters recovery, inflating an
    off-diagonal entry is conservative for leakage.
    """
    from scipy.spatial import cKDTree

    xy = np.asarray(adata.obsm[spatial_key], dtype=np.float64)
    lab = np.asarray(adata.obs[library_key]).astype(str)
    n = xy.shape[0]
    if R is None:
        R = float(np.ptp(xy[:, 1])) + 1.0
    buffer = min(3.0 * float(xi), float(R) / 16.0)

    tile_of = np.zeros(n, dtype=np.int64)
    base = 0
    for u in pd.unique(lab):
        g = np.flatnonzero(lab == u)
        x, y = xy[g, 0], xy[g, 1]
        bx = np.clip(((x - x.min()) / max(np.ptp(x), 1e-9) * n_tiles).astype(int), 0, n_tiles - 1)
        by = np.clip(((y - y.min()) / max(np.ptp(y), 1e-9) * n_tiles).astype(int), 0, n_tiles - 1)
        tile_of[g] = base + by * n_tiles + bx
        base += n_tiles * n_tiles

    uniq = np.unique(tile_of)
    fold_of_tile = {t: i % n_folds for i, t in enumerate(uniq)}   # round-robin
    fold_of_cell = np.array([fold_of_tile[t] for t in tile_of])

    folds, n_buffered = [], []
    for f in range(n_folds):
        te = np.flatnonzero(fold_of_cell == f)
        cand = np.flatnonzero(fold_of_cell != f)
        if te.size == 0 or cand.size == 0:
            continue
        if buffer > 0:
            d, _ = cKDTree(xy[te]).query(xy[cand], k=1)
            keep = d > buffer
        else:
            keep = np.ones(cand.size, dtype=bool)
        n_buffered.append(int((~keep).sum()))
        folds.append((cand[keep], te))

    if not return_meta:
        return folds
    meta = dict(
        xi=float(xi), buffer=float(buffer), R=float(R),
        buffer_ratio=float(buffer / max(3.0 * float(xi), 1e-9)),
        under_buffered=bool(buffer < 3.0 * float(xi) - 1e-9),
        n_folds=len(folds), n_tiles=int(uniq.size),
        mean_train=float(np.mean([len(t) for t, _ in folds])) if folds else 0.0,
        mean_test=float(np.mean([len(e) for _, e in folds])) if folds else 0.0,
        mean_dropped_to_buffer=float(np.mean(n_buffered)) if n_buffered else 0.0,
        bias_note=("under-buffering INFLATES R^2: it flatters a diagonal (recovery) "
                   "entry and is conservative for an off-diagonal (leakage) entry"),
    )
    return folds, meta


def assign_cv_blocks(adata, n_folds: int = 5, n_tiles: int = 5, key: str = "cv_block",
                     library_key: str = "slice_id", spatial_key: str = "spatial"):
    """Write the round-robin fold id into ``adata.obs[key]``."""
    xy = np.asarray(adata.obsm[spatial_key], dtype=np.float64)
    lab = np.asarray(adata.obs[library_key]).astype(str)
    tile_of = np.zeros(adata.n_obs, dtype=np.int64)
    base = 0
    for u in pd.unique(lab):
        g = np.flatnonzero(lab == u)
        x, y = xy[g, 0], xy[g, 1]
        bx = np.clip(((x - x.min()) / max(np.ptp(x), 1e-9) * n_tiles).astype(int), 0, n_tiles - 1)
        by = np.clip(((y - y.min()) / max(np.ptp(y), 1e-9) * n_tiles).astype(int), 0, n_tiles - 1)
        tile_of[g] = base + by * n_tiles + bx
        base += n_tiles * n_tiles
    uniq = np.unique(tile_of)
    fmap = {t: i % n_folds for i, t in enumerate(uniq)}
    adata.obs[key] = np.array([fmap[t] for t in tile_of], dtype=np.int32)
    return adata.obs[key].values


