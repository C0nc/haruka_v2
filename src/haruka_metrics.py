def categorical_probe(Z, y, folds, seed=0, d_probe=None, k_neighbors=15):
    """Balanced accuracy + macro-F1 for logistic and kNN probes on the whitened latent.

    Chance (``1 / n_classes``) is returned alongside, because a balanced accuracy
    is uninterpretable without it.
    """
    from sklearn.linear_model import LogisticRegression
    from sklearn.metrics import balanced_accuracy_score, f1_score
    from sklearn.neighbors import KNeighborsClassifier

    Z = np.asarray(Z, np.float64)
    y = np.asarray(y).astype(str)
    classes = np.unique(y)
    res = {m: {"balanced_accuracy": [], "macro_f1": []} for m in ("logistic", "knn")}
    cache: dict = {}
    for fi, (tr, te) in enumerate(folds):
        if tr.size < 20 or te.size < 5 or np.unique(y[tr]).size < 2:
            continue
        key = (fi, d_probe)
        if key not in cache:
            cache[key] = whiten_fit(Z[tr], d_probe=d_probe)[0]
        Xtr, Xte = cache[key](Z[tr]), cache[key](Z[te])
        for name, clf in (
            ("logistic", LogisticRegression(max_iter=1000)),
            ("knn", KNeighborsClassifier(n_neighbors=min(k_neighbors, max(1, tr.size - 1)))),
        ):
            p = clf.fit(Xtr, y[tr]).predict(Xte)
            res[name]["balanced_accuracy"].append(balanced_accuracy_score(y[te], p))
            res[name]["macro_f1"].append(f1_score(y[te], p, average="macro", zero_division=0))
    out = {m: {k: float(np.mean(v)) if v else float("nan") for k, v in d.items()}
           for m, d in res.items()}
    out["chance"] = float(1.0 / max(classes.size, 1))
    out["n_classes"] = int(classes.size)
    return out


def salient_auroc_within_disease(latents: dict, adata, label_col="gt_lesion",
                                 condition_col="condition", disease_label="disease",
                                 folds=None, seed=0, d_probe=None):
    """Lesion AUROC computed WITHIN THE DISEASE SLICE ONLY.

    Across slices this is confounded with batch and depth and would be trivially
    inflated: ``s`` is NOT zeroed inside ``get_latent_representation`` (the zeroing
    happens on the SAMPLE inside ``inference()``), so a cross-slice score would
    mostly measure "does the latent know which slice this is".

    The background latent's AUROC for the same task is reported too and should sit
    near 0.5.

    **AUROC is averaged ACROSS folds, not computed on pooled probabilities.** The
    lesion is a compact disc and the folds are spatially blocked, so fold
    prevalence varies wildly (measured: 37 vs 295 vs 198 positives out of ~750).
    Logistic regression calibrates to each fold's training prevalence, so
    concatenating raw probabilities mixes incompatible calibrations and destroys
    the ranking: pooled gave 0.588 where the mean per-fold AUROC was 0.687, and it
    pushed a no-information latent to 0.387 -- below chance, which is the
    signature of the artefact rather than of anti-predictive information.

    Note the ceiling. The salient truth is ``t = a_i * b + sigma_t * nu_i`` with
    ``sigma_t = 0.6`` against ``a_i`` in [0, 1], and the label is ``a_i > 0.5``, so
    even the noiseless truth only reaches AUROC ~0.77. Read any measured value
    against that, not against 1.0.
    """
    from sklearn.linear_model import LogisticRegression
    from sklearn.metrics import roc_auc_score

    dis = np.flatnonzero(np.asarray(adata.obs[condition_col]).astype(str) == disease_label)
    y = np.asarray(adata.obs[label_col]).astype(int)
    out: dict[str, Any] = {}
    per_fold: dict[str, list] = {}
    for name, Z in latents.items():
        Z = np.asarray(Z, np.float64)
        aucs = []
        fl = folds or [(dis[: int(0.8 * dis.size)], dis[int(0.8 * dis.size):])]
        for tr, te in fl:
            tr = np.intersect1d(tr, dis)
            te = np.intersect1d(te, dis)
            if tr.size < 20 or te.size < 5 or np.unique(y[tr]).size < 2 \
               or np.unique(y[te]).size < 2:
                continue
            t = whiten_fit(Z[tr], d_probe=d_probe)[0]
            clf = LogisticRegression(max_iter=1000).fit(t(Z[tr]), y[tr])
            aucs.append(float(roc_auc_score(y[te], clf.predict_proba(t(Z[te]))[:, 1])))
        out[name] = float(np.mean(aucs)) if aucs else float("nan")
        per_fold[name] = aucs
    out["_per_fold"] = per_fold
    out["_sd"] = {k: (float(np.std(v)) if v else float("nan")) for k, v in per_fold.items()}
    out["_note"] = ("within-disease only, mean of per-fold AUROC; z_bg should sit "
                    "near 0.5 and the noiseless-truth ceiling is ~0.77")
    return out


def domain_recovery(adata, use_rep, truth_cols=("gt_niche_label", "cell_type",
                                                "gt_lesion", "true_domain"),
                    k_list=None, k_true=4, n_seeds=5, method="gmm", seed0=0,
                    n_pcs=50, scale=True):
    """ARI **and** AMI against each truth SEPARATELY, over K and 5 clustering seeds.

    AMI as well as ARI because ARI is sensitive to cluster-count mismatch. Each
    truth separately because a joint-label-only ARI hides which factor the
    clustering actually keyed on.

    ``FastCluster(method='gmm')`` is the default: graded spatial domains are
    exactly the elongated, anisotropic structure k-means handles worst. Falls back
    to k-means if cellcharter is unavailable.

    **Continuous R^2 is primary; ARI is corroborating, never decisive** -- the
    binning of a continuous truth into labels is arbitrary.
    """
    from sklearn.metrics import adjusted_mutual_info_score, adjusted_rand_score

    try:
        from haruka_cluster import FastCluster
    except Exception:  # pragma: no cover
        FastCluster = None

    if k_list is None:
        k_list = [max(2, k_true - 2), k_true, k_true + 2]
    rows = []
    for K in k_list:
        for s in range(n_seeds):
            if FastCluster is not None:
                try:
                    lab = np.asarray(FastCluster(n_clusters=K, method=method,
                                                 random_state=seed0 + s, n_pcs=n_pcs,
                                                 scale=scale).fit_predict(adata, use_rep=use_rep))
                except Exception:
                    lab = _fallback_kmeans(adata, use_rep, K, seed0 + s, n_pcs, scale)
            else:
                lab = _fallback_kmeans(adata, use_rep, K, seed0 + s, n_pcs, scale)
            lab = np.asarray(lab).astype(int)
            # coherence is a property of the LABELLING, not of any truth, so it is
            # computed once per clustering rather than once per (clustering, truth)
            coh = spatial_coherence(adata, lab)
            for col in truth_cols:
                if col not in adata.obs.columns:
                    continue
                t = np.asarray(adata.obs[col]).astype(str)
                rows.append(dict(K=K, seed=seed0 + s, truth=col,
                                 ARI=adjusted_rand_score(t, lab),
                                 AMI=adjusted_mutual_info_score(t, lab),
                                 coherence=coh))
    df = pd.DataFrame(rows)
    if df.empty:
        return df, df
    agg = df.groupby(["truth", "K"])[["ARI", "AMI", "coherence"]].agg(["mean", "std"])
    return df, agg


def _fallback_kmeans(adata, use_rep, K, seed, n_pcs, scale):
    from sklearn.cluster import KMeans
    from sklearn.decomposition import PCA

    X = np.asarray(adata.obsm[use_rep] if use_rep else adata.X, np.float64)
    if scale:
        sd = X.std(0)
        sd[sd < 1e-9] = 1.0
        X = (X - X.mean(0)) / sd
    if n_pcs and n_pcs < X.shape[1]:
        X = PCA(n_components=min(n_pcs, min(X.shape) - 1), random_state=seed).fit_transform(X)
    return KMeans(n_clusters=K, n_init=10, random_state=seed).fit_predict(X)


def spatial_coherence(adata, labels, row_key="array_row", col_key="array_col",
                      library_key="slice_id"):
    """Fraction of a cell's 8 lattice neighbours sharing its label.

    Catches a respectable ARI achieved with salt-and-pepper labels. Compare the
    fitted value against the same statistic computed on the TRUTH.
    """
    lab = pd.factorize(np.asarray(labels).astype(str))[0]
    rr = np.asarray(adata.obs[row_key], np.int64)
    cc = np.asarray(adata.obs[col_key], np.int64)
    sl = pd.factorize(np.asarray(adata.obs[library_key]).astype(str))[0].astype(np.int64)

    # Dense (slice, row, col) -> label lookup. Vectorised rather than a per-cell
    # dict walk because domain_recovery calls this once per clustering across a
    # K sweep and 5 seeds, where an 8n-lookup Python loop dominates the runtime.
    nr, nc = int(rr.max()) + 3, int(cc.max()) + 3
    grid = np.full((int(sl.max()) + 1, nr, nc), -1, dtype=np.int64)
    grid[sl, rr + 1, cc + 1] = lab
    same = tot = 0
    for dr in (-1, 0, 1):
        for dc in (-1, 0, 1):
            if dr == 0 and dc == 0:
                continue
            nb = grid[sl, rr + 1 + dr, cc + 1 + dc]
            valid = nb >= 0
            tot += int(valid.sum())
            same += int((valid & (nb == lab)).sum())
    return float(same / tot) if tot else float("nan")


