"""Evaluation metrics for the NICHE-CONFOUND spatial benchmark.

Companion to :mod:`haruka_sim`. Everything here is written against one hard
constraint: **a VAE latent is identified only up to an invertible
reparametrisation** -- a linear map at minimum, a diffeomorphism in general.
That single fact rules out most of the obvious things one would reach for, and
the rulings are enforced here rather than left to the caller's discipline:

* **Per-dimension Pearson/Spearman between latent and truth is forbidden.** It is
  not invariant to rotation and is meaningless for a VAE latent. No function in
  this module computes one.
* **The linear probe is unregularised multi-output OLS on a PCA-whitened latent.**
  That is *exactly* invariant to any invertible linear map. Ridge is only
  approximately so, and is offered as a sensitivity check, never as the primary.
* **The headline probe is a 2-hidden-layer MLP on the same whitened latent**,
  because smooth reparametrisation is the actual identifiability class. The
  linear-vs-nonlinear gap is itself reported: it says whether the factorisation
  is linearly decodable or merely present.
* **Latents of different width are not compared at face value.** Every entry is
  computed twice -- at full width, and with each latent PCA-reduced to a common
  ``d_probe``. The headline uses the common width.
* **Every R^2 is printed with a permutation floor, and the quantity that carries
  a claim is ``R^2 - floor``.** The floor is generated by permuting whole TILES,
  which preserves the truth's spatial autocorrelation. A cell-wise permutation is
  the wrong null here: it destroys the autocorrelation and yields an artificially
  low floor, which manufactures significance.
* **Cross-validation is spatially blocked with a truth-specific buffer.** With a
  smooth truth and random folds, a cell's own neighbours land in training; since
  the niche IS a function of neighbours the probe near-interpolates, and the
  background latent scores above its theoretical zero purely via position.

Buffering is deliberately unequal across truths and the spec is explicit about
the bias direction: under-buffering INFLATES R^2, which FLATTERS a diagonal
(recovery) entry but is CONSERVATIVE for an off-diagonal (leakage) entry. Columns
whose buffer could not reach ``3*xi`` are flagged ``under_buffered`` and their
R^2 is an upper bound.

One consequence deserves its own warning, because it bites every dependence
statistic here. **The relevant sample size is the number of independent spatial
PATCHES, not the number of cells.** On a 48-site lattice with an autocorrelation
range of 4 there are ~36 patches per slice, so SE(r) is ~0.12 rather than the
1/sqrt(4240) = 0.015 one would assume; measured on factors that are independent
BY CONSTRUCTION, max |r| reached 0.15 and a cell-permutation null put its 95th
percentile at 0.047. Any fixed threshold, and any cell-wise permutation null,
therefore declares independent factors dependent. Every dependence measure in
this module (``distance_correlation_null``, ``hsic_pvalue``, ``cv_cca``,
``permutation_floor``) takes a tile null for exactly this reason, and the same
quantities computed at R=128 come out cleanly negative.

Typical use::

    import haruka_metrics as hm

    folds, meta = hm.blocked_cv_folds(adata, xi=xi_v, return_meta=True)
    tiles = hm.tile_ids(adata)
    res = hm.recovery_leakage_matrix(latents, truths, folds, tiles, d_probe=10)
    print(res["adjusted"]);  print(hm.disentanglement_summary(res["adjusted"]))
"""

