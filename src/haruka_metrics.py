def recovery_leakage_matrix(
    latents: dict[str, np.ndarray],
    truths: dict[str, np.ndarray],
    folds_by_truth: dict[str, Sequence[tuple[np.ndarray, np.ndarray]]] | Sequence,
    tiles: np.ndarray,
    d_probe: int | None = 10,
    kind: str = "mlp",
    n_perm: int = 50,
    seed: int = 0,
    also_full_width: bool = True,
    also_linear: bool = True,
    verbose: bool = False,
    mlp_kwargs: dict | None = None,
):
    """``M[a, b] = R^2(latent a -> truth b) - floor_perm[a, b]``, ALWAYS reported in full.

    ``folds_by_truth`` may be a single fold list, or a dict mapping truth name ->
    fold list so that each truth gets its own buffer (``xi`` differs per factor).

    Returned dict:

    ``raw``            R^2 at the common ``d_probe`` width (headline input)
    ``floor``          tile-permutation floor for the same (latent, truth) pair
    ``adjusted``       ``raw - floor`` -- the quantity that carries a claim
    ``raw_full``       R^2 at each latent's full width (not width-matched)
    ``linear``         unregularised-OLS R^2 at ``d_probe`` width
    ``lin_nl_gap``     ``raw - linear``: is the factorisation linearly decodable,
                       or merely present?
    ``components``     per-cell numerator/denominator for the block bootstrap

    ``F_decoy`` is an ANTI-TARGET column, not a factor: high ``M[z_sp, F_decoy]``
    with low ``M[z_sp, F_niche]`` is a FAILURE regardless of every other number.
    It is excluded from :func:`disentanglement_summary`.
    """
    lat_names = list(latents)
    tru_names = list(truths)

    def _folds(b):
        if isinstance(folds_by_truth, dict):
            return folds_by_truth[b]
        return folds_by_truth

    raw = pd.DataFrame(np.nan, index=lat_names, columns=tru_names)
    floor = raw.copy()
    raw_full = raw.copy()
    linear = raw.copy()
    comps: dict[tuple[str, str], dict] = {}

    for a in lat_names:
        Z = np.asarray(latents[a])
        # Caches are keyed on the fold-list identity as well as the fold index, so
        # they stay correct even though each truth carries its own buffered folds.
        cache_common: dict = {}
        cache_full: dict = {}
        for b in tru_names:
            F = np.asarray(truths[b])
            fl = _folds(b)
            r2, comp = probe_r2(Z, F, fl, kind=kind, d_probe=d_probe, seed=seed,
                                tiles=tiles, return_components=True,
                                whiteners=cache_common, mlp_kwargs=mlp_kwargs)
            raw.loc[a, b] = r2
            comps[(a, b)] = comp
            if n_perm > 0:
                floor.loc[a, b] = permutation_floor(
                    Z, F, fl, tiles, kind=kind, d_probe=d_probe, n_perm=n_perm,
                    seed=seed, whiteners=cache_common, mlp_kwargs=mlp_kwargs)[0]
            else:
                floor.loc[a, b] = 0.0
            if also_full_width:
                raw_full.loc[a, b] = probe_r2(Z, F, fl, kind=kind, d_probe=None,
                                              seed=seed, whiteners=cache_full,
                                              mlp_kwargs=mlp_kwargs)
            if also_linear:
                linear.loc[a, b] = probe_r2(Z, F, fl, kind="ols", d_probe=d_probe,
                                            seed=seed, whiteners=cache_common)
            if verbose:
                print(f"    {a:>8s} -> {b:<9s} r2={raw.loc[a, b]:+.4f} "
                      f"floor={floor.loc[a, b]:+.4f} adj={raw.loc[a, b] - floor.loc[a, b]:+.4f}")

    return dict(
        raw=raw, floor=floor, adjusted=raw - floor, raw_full=raw_full,
        linear=linear, lin_nl_gap=raw - linear, components=comps,
        d_probe=d_probe, kind=kind, n_perm=n_perm,
        note=("adjusted = raw - tile-permutation floor; only `adjusted` carries a "
              "claim. F_decoy is an anti-target column, never a factor."),
    )


def disentanglement_summary(
    M: pd.DataFrame,
    pairing: dict[str, str] | None = None,
    exclude: Sequence[str] = ("F_decoy",),
):
    """DCI-D / DCI-C / informativeness / MIG / SDS on the floor-adjusted matrix.

    Computed on the square sub-matrix after dropping the anti-target column(s).
    Clipping at 0 applies ONLY inside the entropy computations; the raw and
    floor-subtracted values are reported unclipped elsewhere.

    ``SDS = mean_a ( M[a,a] - max_{b != a} M[a,b] )`` in ``[-1, 1]`` is the single
    quotable scalar. **Never quote it without the full matrix.**
    """
    cols = [c for c in M.columns if c not in exclude]
    S = M[cols].copy()
    P = np.clip(S.to_numpy(dtype=float), 0.0, None)
    out: dict[str, Any] = {}

    def _ent_score(mat, axis):
        n_other = mat.shape[1 - axis]
        if n_other < 2:
            return float("nan"), np.zeros(mat.shape[axis])
        tot = mat.sum(axis=1 - axis)
        sc = np.zeros(mat.shape[axis])
        for i in range(mat.shape[axis]):
            v = mat[i] if axis == 0 else mat[:, i]
            s = v.sum()
            if s <= 0:
                sc[i] = 0.0
                continue
            p = v / s
            p = p[p > 0]
            sc[i] = 1.0 - float(-(p * np.log(p)).sum() / math.log(n_other))
        w = tot / tot.sum() if tot.sum() > 0 else np.full(mat.shape[axis], 1.0 / mat.shape[axis])
        return float((w * sc).sum()), sc

    out["DCI_D_modularity"], per_lat = _ent_score(P, 0)
    out["DCI_C_completeness"], per_fac = _ent_score(P, 1)
    out["per_latent_modularity"] = dict(zip(S.index, per_lat))
    out["per_factor_completeness"] = dict(zip(cols, per_fac))
    out["informativeness"] = float(np.mean(S.to_numpy(dtype=float).max(axis=0)))

    # MIG uses the CLIPPED matrix so it stays in [0, 1]. On the raw matrix a
    # negative runner-up makes (best - second)/best exceed 1, which is not a
    # meaningful "compactness".
    mig = {}
    for j, b in enumerate(cols):
        v = np.sort(P[:, j])[::-1]
        mig[b] = float((v[0] - v[1]) / v[0]) if v.size > 1 and v[0] > 0 else float("nan")
    out["MIG_compactness"] = mig

    if pairing is None:
        pairing = {"z_bg": "F_int", "s_sal": "F_sal", "z_sp": "F_niche"}
    sds = []
    for a, b in pairing.items():
        if a not in S.index or b not in cols:
            continue
        row = S.loc[a]
        off = [row[c] for c in cols if c != b]
        sds.append(float(row[b] - (max(off) if off else 0.0)))
    out["SDS"] = float(np.mean(sds)) if sds else float("nan")
    out["SDS_terms"] = dict(zip([a for a in pairing if a in S.index], sds))
    out["note"] = "never quote SDS without the full recovery/leakage matrix"
    return out


def coordinate_floor(adata, truths, folds_by_truth, tiles, kind="mlp",
                     d_probe=None, n_perm=0, seed=0, spatial_key="spatial",
                     subset=None, mlp_kwargs=None):
    """``R^2((x, y) -> F)`` for every truth, same blocked CV, same probe.

    A spatial latent's leakage onto the salient factor cannot go below this: the
    lesion is spatially compact, so ANY latent encoding position scores on it.
    **Only excess over the coordinate floor counts as leakage.**

    ``subset`` (a boolean mask or index array) restricts the probe, and for the
    SALIENT factor you almost always want it set to the disease cells. Both slices
    deliberately occupy an identical coordinate frame, so pooled across slices
    ``(x, y)`` cannot tell control from disease; it sees one cell with ``t = 0``
    and one with ``t = a(x,y)*b + noise`` at the same position and can only predict
    their average. The pooled floor is therefore diluted roughly two-fold and is
    NOT the right bar for judging salient leakage -- the within-disease floor is.
    """
    XY = np.asarray(adata.obsm[spatial_key], dtype=np.float64)
    keep = None
    if subset is not None:
        keep = np.flatnonzero(subset) if np.asarray(subset).dtype == bool \
            else np.asarray(subset)
    out = {}
    cache: dict = {}
    for b, F in truths.items():
        fl = folds_by_truth[b] if isinstance(folds_by_truth, dict) else folds_by_truth
        if keep is not None:
            fl = [(np.intersect1d(tr, keep), np.intersect1d(te, keep)) for tr, te in fl]
        r2 = probe_r2(XY, F, fl, kind=kind, d_probe=d_probe, seed=seed,
                      whiteners=cache, mlp_kwargs=mlp_kwargs)
        fo = 0.0
        if n_perm > 0:
            fo = permutation_floor(XY, F, fl, tiles, kind=kind, d_probe=d_probe,
                                   n_perm=n_perm, seed=seed, whiteners=cache,
                                   mlp_kwargs=mlp_kwargs)[0]
        out[b] = dict(r2=r2, floor=fo, adjusted=r2 - fo,
                      n=int(len(keep)) if keep is not None else int(adata.n_obs))
    return out


def delta_niche(r2_spatial, r2_ablation, r2_own_row_oracle, floor_perm):
    """The headline claim.

    ``Delta_niche = R2(z_sp -> v) - max(R2(z_bg[ablation] -> v), R2(eta -> v), floor_perm)``

    ``R2(eta -> v)`` is the OWN-ROW ORACLE on the noiseless log-rate: exactly 0 at
    ``rho = 0`` by the theorem, and the correct bar at ``rho > 0`` (it upper-bounds
    any probe on the noisy counts by data processing).

    ``Delta_niche > 0`` with a TILE block-bootstrap CI excluding 0, across >= 5
    simulator seeds, is the only evidence the branch extracts information a
    non-spatial model provably cannot.

    Note gotcha G4: ``n_spatial_latent=0`` is a MECHANISM ablation, not a
    "same z +/- spatial" contrast. Gradients flow from the GAT into the background
    encoder, so the ablation changes that encoder too. Say so when reporting.
    """
    bar = float(np.nanmax([r2_ablation, r2_own_row_oracle, floor_perm]))
    return dict(delta=float(r2_spatial - bar), bar=bar, r2_spatial=float(r2_spatial),
                r2_ablation=float(r2_ablation), r2_own_row_oracle=float(r2_own_row_oracle),
                floor_perm=float(floor_perm))


