def _double_center(d):
    return d - d.mean(0, keepdims=True) - d.mean(1, keepdims=True) + d.mean()


def _dcor_from_centered(A, B):
    dcov2 = float((A * B).mean())
    den = math.sqrt(float((A * A).mean()) * float((B * B).mean()))
    if den <= 0:
        return 0.0
    return float(math.sqrt(max(dcov2, 0.0) / den))


def distance_correlation(X, Y, max_cells=5000, seed=0):
    """Distance correlation -- invariant to orthogonal transforms and isotropic scaling.

    Used as the LEAKAGE measure, because leakage is often nonlinear and a linear
    probe would miss it. O(n^2), so subsampled; also floor it against the
    tile-permutation null (see :func:`distance_correlation_null`) before reading
    anything into it -- dCor is non-negative and upward-biased at the small
    EFFECTIVE n that spatial autocorrelation leaves behind.
    """
    X = np.asarray(X, np.float64)
    Y = np.asarray(Y, np.float64)
    if X.ndim == 1:
        X = X[:, None]
    if Y.ndim == 1:
        Y = Y[:, None]
    n = X.shape[0]
    if n > max_cells:
        sub = np.sort(np.random.default_rng(seed).choice(n, max_cells, replace=False))
        X, Y = X[sub], Y[sub]
    return _dcor_from_centered(_double_center(np.sqrt(_sqdist(X, X))),
                               _double_center(np.sqrt(_sqdist(Y, Y))))


def distance_correlation_null(X, Y, tiles, n_perm=30, seed=0, q=95.0):
    """Observed dCor plus its autocorrelation-preserving tile-permutation null.

    The distance matrices are built ONCE and the permutation is applied as an
    index into them, so ``n_perm`` draws cost O(n^2) each instead of rebuilding an
    O(n^2 d) distance matrix every time.
    """
    X = np.asarray(X, np.float64)
    Y = np.asarray(Y, np.float64)
    if X.ndim == 1:
        X = X[:, None]
    if Y.ndim == 1:
        Y = Y[:, None]
    dX = np.sqrt(_sqdist(X, X))
    dY = np.sqrt(_sqdist(Y, Y))
    A = _double_center(dX)
    obs = _dcor_from_centered(A, _double_center(dY))
    rng = np.random.default_rng(seed)
    nulls = np.empty(int(n_perm))
    for i in range(int(n_perm)):
        p = tile_permute_index(np.asarray(tiles), rng)
        nulls[i] = _dcor_from_centered(A, _double_center(dY[np.ix_(p, p)]))
    p95 = float(np.percentile(nulls, q))
    return dict(dcor=float(obs), dcor_null_p95=p95, dcor_excess=float(obs - p95),
                n=int(X.shape[0]), n_perm=int(n_perm))


def hsic_pvalue(X, Y, seed=0, n_perm=200, max_cells=1000, tiles=None):
    """HSIC with an RBF median-heuristic kernel and a permutation p-value.

    **Pass ``tiles`` whenever X or Y is spatially autocorrelated.** The default
    cell-wise permutation destroys autocorrelation, so its null is far too narrow
    and the p-value is ANTI-CONSERVATIVE. This is measured, not asserted: pairing
    factors drawn from 30 different simulator seeds -- independent by construction,
    with realistic autocorrelation -- gives

        cell-permutation null:  30.0% of p-values below 0.05   (6x nominal)
        tile-permutation null:   6.7% of p-values below 0.05   (nominal 5%)

    so the tile null is calibrated and the cell null would have you declare
    dependence in nearly a third of provably independent pairs. The same argument
    applies to :func:`distance_correlation`, which is why its floor is a tile null
    too (``distance_correlation_null``).

    Since the audit tests 6 factor pairs at once, apply a multiplicity correction
    before calling any single p-value a finding: at a calibrated 6.7% rate, one
    hit in six is the expected outcome, not evidence.
    """
    rng = np.random.default_rng(seed)
    X = np.asarray(X, np.float64)
    Y = np.asarray(Y, np.float64)
    if X.ndim == 1:
        X = X[:, None]
    if Y.ndim == 1:
        Y = Y[:, None]
    n = X.shape[0]
    if n > max_cells:
        sub = np.sort(rng.choice(n, max_cells, replace=False))
        X, Y, n = X[sub], Y[sub], max_cells
        tiles = None if tiles is None else np.asarray(tiles)[sub]

    def _K(Z):
        d2 = _sqdist(Z, Z)
        pos = d2[d2 > 0]
        med = np.median(pos) if pos.size else 1.0
        return np.exp(-d2 / max(med, 1e-12))

    def _center(K):
        # H K H by mean subtraction: O(n^2). Doing it as two matmuls would be
        # O(n^3) and, inside the permutation loop, is what makes a tile null slow
        # enough to look broken.
        return K - K.mean(0, keepdims=True) - K.mean(1, keepdims=True) + K.mean()

    Kc = _center(_K(X))
    L = _K(Y)
    stat = float((Kc * _center(L)).sum())
    ge = 0
    for _ in range(n_perm):
        # permute the KERNEL by index rather than recomputing it from permuted
        # values -- identical result, O(n^2) instead of O(n^2 d) + a fresh median
        p = (rng.permutation(n) if tiles is None
             else tile_permute_index(np.asarray(tiles), rng))
        ge += float((Kc * _center(L[np.ix_(p, p)])).sum()) >= stat
    return dict(hsic=stat / (n * n), p=(ge + 1) / (n_perm + 1), n=n,
                null="tile permutation" if tiles is not None else "cell permutation")


def _reg_cca(Xtr, Ytr, alpha=1e-3, k=None):
    """Regularised CCA via the whitened cross-covariance SVD.

    sklearn's ``CCA`` is NIPALS with no regularisation; with a 256-d latent and
    30k cells the unregularised solution is numerically unstable and its null is
    nowhere near zero, so the ridge term is not optional.
    """
    Xc, Yc = Xtr - Xtr.mean(0), Ytr - Ytr.mean(0)
    n = max(Xc.shape[0] - 1, 1)
    Sxx = Xc.T @ Xc / n + alpha * np.eye(Xc.shape[1])
    Syy = Yc.T @ Yc / n + alpha * np.eye(Yc.shape[1])
    Sxy = Xc.T @ Yc / n

    def _isqrt(S):
        w, V = np.linalg.eigh(S)
        w = np.maximum(w, 1e-12)
        return V @ np.diag(1.0 / np.sqrt(w)) @ V.T

    Rx, Ry = _isqrt(Sxx), _isqrt(Syy)
    U, s, Vt = np.linalg.svd(Rx @ Sxy @ Ry, full_matrices=False)
    if k is None:
        k = min(Xc.shape[1], Yc.shape[1])
    k = int(min(k, s.size))
    return Rx @ U[:, :k], Ry @ Vt[:k].T, Xtr.mean(0), Ytr.mean(0)


def cv_cca(X, Y, folds, alpha=1e-3, k=None, tiles=None, n_perm=200, seed=0, q=95.0):
    """Out-of-fold mean canonical correlation, minus a tile-permutation null.

    Fitted on train, EVALUATED OUT OF FOLD. With 256 dims and 30k cells the
    uncorrected CCA null is far from zero, which is why the null subtraction is
    part of the definition rather than a nicety.
    """
    X = np.asarray(X, np.float64)
    Y = np.asarray(Y, np.float64)
    if Y.ndim == 1:
        Y = Y[:, None]

    def _score(Ymat, s):
        vals = []
        for tr, te in folds:
            if tr.size < 20 or te.size < 5:
                continue
            Wx, Wy, mx, my = _reg_cca(X[tr], Ymat[tr], alpha=alpha, k=k)
            A, B = (X[te] - mx) @ Wx, (Ymat[te] - my) @ Wy
            cs = []
            for j in range(A.shape[1]):
                a, b = A[:, j], B[:, j]
                if a.std() < 1e-12 or b.std() < 1e-12:
                    cs.append(0.0)
                else:
                    cs.append(abs(float(np.corrcoef(a, b)[0, 1])))
            vals.append(np.mean(cs) if cs else 0.0)
        return float(np.mean(vals)) if vals else float("nan")

    obs = _score(Y, seed)
    if tiles is None or n_perm <= 0:
        return dict(cca=obs, null_p95=float("nan"), adjusted=float("nan"))
    rng = np.random.default_rng(seed + 7)
    nulls = [_score(tile_permute(Y, np.asarray(tiles), rng), seed) for _ in range(int(n_perm))]
    nulls = np.asarray([v for v in nulls if np.isfinite(v)])
    p95 = float(np.percentile(nulls, q)) if nulls.size else float("nan")
    return dict(cca=obs, null_p95=p95, adjusted=obs - p95, n_perm=int(nulls.size))


def latent_stability(Z1, Z2, folds, alpha=1e-3, k=10, seed=0):
    """Out-of-fold CV-CCA between two model seeds' spatial latents.

    An unstable latent is not a discovery however good its R^2.
    """
    return cv_cca(np.asarray(Z1), np.asarray(Z2), folds, alpha=alpha, k=k,
                  tiles=None, n_perm=0, seed=seed)["cca"]


