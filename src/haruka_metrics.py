class ResourceProbe:
    """Wall clock, peak CUDA memory and peak host RSS around a block.

    ``torch.cuda.max_memory_allocated`` AND ``max_memory_reserved`` are both
    reported after ``reset_peak_memory_stats``. **nvidia-smi is broken in this
    environment (NVML version mismatch) and is never called.**

    Usage::

        with ResourceProbe("train") as p:
            model.train(...)
        print(p.report)
    """

    def __init__(self, name="block", device=None, sync=True):
        self.name, self.device, self.sync = name, device, sync
        self.report: dict[str, Any] = {}

    def _rss(self):
        try:
            import resource

            kb = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
            return kb / (1024.0 ** 2)  # Linux reports KiB
        except Exception:
            return float("nan")

    def __enter__(self):
        self._t0 = time.perf_counter()
        self._rss0 = self._rss()
        try:
            import torch

            self._torch = torch
            if torch.cuda.is_available():
                torch.cuda.synchronize()
                torch.cuda.reset_peak_memory_stats(self.device)
        except Exception:
            self._torch = None
        return self

    def __exit__(self, *exc):
        t = self._torch
        if t is not None and t.cuda.is_available() and self.sync:
            t.cuda.synchronize()
        self.report = dict(
            name=self.name,
            wall_s=time.perf_counter() - self._t0,
            peak_host_rss_gb=self._rss(),
            host_rss_delta_gb=self._rss() - self._rss0,
            peak_cuda_alloc_gb=(t.cuda.max_memory_allocated(self.device) / 1024 ** 3
                                if t is not None and t.cuda.is_available() else float("nan")),
            peak_cuda_reserved_gb=(t.cuda.max_memory_reserved(self.device) / 1024 ** 3
                                   if t is not None and t.cuda.is_available() else float("nan")),
        )
        return False

    def with_scale(self, n_cells, n_params=None, n_epochs=None):
        """Attach throughput figures so the spatial branch's overhead is an explicit ratio."""
        r = self.report
        r["n_cells"] = int(n_cells)
        r["cells_per_s"] = float(n_cells / r["wall_s"]) if r.get("wall_s") else float("nan")
        if n_epochs:
            r["s_per_epoch"] = float(r["wall_s"] / n_epochs)
        if n_params is not None:
            r["n_params"] = int(n_params)
        return r


def resource_probe(name="block", **kw):
    return ResourceProbe(name=name, **kw)


def count_parameters(module):
    return int(sum(p.numel() for p in module.parameters()))
