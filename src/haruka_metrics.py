class _TorchMLP:
    """2-hidden-layer MLP (256, 128), ReLU, weight-decay 1e-4, Adam 1e-3.

    Early stopping on an inner 20% split OF THE TRAINING FOLD (never the test
    fold), <= 200 epochs. Runs on CUDA when available; ``nvidia-smi`` is broken in
    this environment so device selection never shells out to it.
    """

    def __init__(self, hidden=(256, 128), alpha=1e-4, lr=1e-3, max_epochs=200,
                 batch_size=256, patience=10, val_frac=0.2, seed=0, device=None):
        self.hidden, self.alpha, self.lr = hidden, alpha, lr
        self.max_epochs, self.batch_size = max_epochs, batch_size
        self.patience, self.val_frac, self.seed = patience, val_frac, seed
        self.device = device
        self.net_ = None

    def fit(self, X, Y):
        import torch
        from torch import nn

        dev = self.device or ("cuda" if torch.cuda.is_available() else "cpu")
        torch.manual_seed(self.seed)
        X = np.asarray(X, np.float32)
        Y = np.asarray(Y, np.float32)
        if Y.ndim == 1:
            Y = Y[:, None]
        rng = np.random.default_rng(self.seed)
        idx = rng.permutation(X.shape[0])
        nv = max(1, int(round(self.val_frac * X.shape[0])))
        va, tr = idx[:nv], idx[nv:]
        if tr.size < 2:
            tr, va = idx, idx

        layers, d = [], X.shape[1]
        for h in self.hidden:
            layers += [nn.Linear(d, h), nn.ReLU()]
            d = h
        layers += [nn.Linear(d, Y.shape[1])]
        net = nn.Sequential(*layers).to(dev)
        opt = torch.optim.Adam(net.parameters(), lr=self.lr, weight_decay=self.alpha)
        lossf = nn.MSELoss()

        Xt = torch.as_tensor(X[tr], device=dev)
        Yt = torch.as_tensor(Y[tr], device=dev)
        Xv = torch.as_tensor(X[va], device=dev)
        Yv = torch.as_tensor(Y[va], device=dev)
        bs = min(self.batch_size, max(1, Xt.shape[0]))
        best, best_state, bad = np.inf, None, 0
        gen = torch.Generator(device="cpu")
        gen.manual_seed(self.seed)
        for _ in range(self.max_epochs):
            net.train()
            perm = torch.randperm(Xt.shape[0], generator=gen).to(dev)
            for a in range(0, Xt.shape[0], bs):
                b = perm[a : a + bs]
                opt.zero_grad(set_to_none=True)
                lossf(net(Xt[b]), Yt[b]).backward()
                opt.step()
            net.eval()
            with torch.no_grad():
                v = float(lossf(net(Xv), Yv))
            if v < best - 1e-6:
                best, bad = v, 0
                best_state = {k: t.detach().clone() for k, t in net.state_dict().items()}
            else:
                bad += 1
                if bad >= self.patience:
                    break
        if best_state is not None:
            net.load_state_dict(best_state)
        net.eval()
        self.net_, self._dev, self._d_out = net, dev, Y.shape[1]
        return self

    def predict(self, X):
        import torch

        with torch.no_grad():
            out = self.net_(torch.as_tensor(np.asarray(X, np.float32), device=self._dev))
        return out.cpu().numpy()


def _make_regressor(kind: str, seed: int, n_train: int, krr_max_train: int = 2000,
                    mlp_kwargs: dict | None = None):
    """Return a ``(fit_predict)`` callable for the requested probe family."""
    mlp_kwargs = dict(mlp_kwargs or {})

    if kind == "ols":
        # UNREGULARISED multi-output OLS -- exactly invariant to any invertible
        # linear map of the latent. This is the primary linear probe.
        def f(Xtr, Ytr, Xte):
            A = np.hstack([Xtr, np.ones((Xtr.shape[0], 1))])
            B = np.hstack([Xte, np.ones((Xte.shape[0], 1))])
            coef, *_ = np.linalg.lstsq(A, Ytr, rcond=None)
            return B @ coef
        return f

    if kind == "ridge":
        # SENSITIVITY CHECK ONLY: ridge is only approximately linear-invariant.
        from sklearn.linear_model import RidgeCV

        def f(Xtr, Ytr, Xte):
            m = RidgeCV(alphas=np.logspace(-3, 3, 13)).fit(Xtr, Ytr)
            return m.predict(Xte)
        return f

    if kind == "mlp":
        def f(Xtr, Ytr, Xte):
            try:
                return _TorchMLP(seed=seed, **mlp_kwargs).fit(Xtr, Ytr).predict(Xte)
            except ImportError:  # pragma: no cover - torch is present in this env
                from sklearn.neural_network import MLPRegressor

                m = MLPRegressor(
                    hidden_layer_sizes=(256, 128), activation="relu", solver="adam",
                    alpha=1e-4, learning_rate_init=1e-3, max_iter=200,
                    early_stopping=True, validation_fraction=0.2,
                    n_iter_no_change=10, random_state=seed,
                ).fit(Xtr, Ytr)
                p = m.predict(Xte)
                return p[:, None] if p.ndim == 1 else p
        return f

    if kind == "krr":
        from sklearn.kernel_ridge import KernelRidge
        from sklearn.model_selection import GridSearchCV

        def f(Xtr, Ytr, Xte):
            rng = np.random.default_rng(seed)
            if Xtr.shape[0] > krr_max_train:   # O(n^3) solve; subsample and say so
                sub = rng.choice(Xtr.shape[0], krr_max_train, replace=False)
                Xtr, Ytr = Xtr[sub], Ytr[sub]
            d2 = _sqdist(Xtr, Xtr)
            med = np.median(d2[d2 > 0]) if (d2 > 0).any() else 1.0
            gamma = 1.0 / max(med, 1e-12)          # median heuristic
            gs = GridSearchCV(
                KernelRidge(kernel="rbf", gamma=gamma),
                {"alpha": np.logspace(-4, 2, 7)}, cv=3,
            ).fit(Xtr, Ytr)
            p = gs.predict(Xte)
            return p[:, None] if p.ndim == 1 else p
        return f

    raise ValueError(f"unknown probe kind {kind!r}")


def _sqdist(A, B):
    return np.maximum(
        (A * A).sum(1)[:, None] - 2.0 * (A @ B.T) + (B * B).sum(1)[None, :], 0.0
    )


def _folds_fingerprint(folds):
    """Cheap content-derived identity for a fold list, for safe whitener caching."""
    parts = []
    for tr, te in folds:
        tr = np.asarray(tr)
        te = np.asarray(te)
        parts.append((int(tr.size), int(te.size),
                      int(tr[0]) if tr.size else -1, int(tr[-1]) if tr.size else -1,
                      int(te[0]) if te.size else -1, int(te[-1]) if te.size else -1,
                      int(tr.sum()) if tr.size else 0, int(te.sum()) if te.size else 0))
    return tuple(parts)


def pooled_r2(num: float, den: float) -> float:
    """``R^2 = 1 - sum_d sum_i (F - Fhat)^2 / sum_d sum_i (F - Fbar_train)^2``.

    Pooled over folds (accumulate numerator and denominator, divide once),
    variance-weighted over truth dimensions (squared errors are summed over dims
    without per-dim normalisation, so a high-variance dimension counts more), and
    centred by the TRAIN mean -- using the test mean is optimistically biased.
    """
    return float(1.0 - num / den) if den > 0 else float("nan")


def probe_r2(
    Z: np.ndarray,
    F: np.ndarray,
    folds: Sequence[tuple[np.ndarray, np.ndarray]],
    kind: str = "mlp",
    d_probe: int | None = None,
    seed: int = 0,
    tiles: np.ndarray | None = None,
    return_components: bool = False,
    whiteners: dict | None = None,
    mlp_kwargs: dict | None = None,
    var_keep: float = _VAR_KEEP,
):
    """Cross-validated R^2 of ``Z -> F`` under the spec's exact definition.

    ``Z`` is PCA-whitened on each training fold (optionally truncated to
    ``d_probe`` for width-matched comparison), then a probe of family ``kind`` is
    fitted and scored out of fold.

    ``whiteners`` may be a dict used as a cache; it is filled in on first use. The
    whitener depends only on (latent, fold, d_probe) and never on the truth, so
    reusing it across the 50 permutation draws is exact, and is the difference
    between a 5-minute and a 90-minute matrix. **The cache must not be shared
    across DIFFERENT fold sets**: each truth gets its own buffer, so "fold 0" of
    the niche folds is a different training set from "fold 0" of the intrinsic
    folds, and a cache keyed on the index alone would silently hand back a
    whitener fitted on the wrong rows. The cache therefore carries a fingerprint of
    the fold set it was built for and resets itself when handed a different one.
    (The fingerprint is derived from the fold CONTENT rather than ``id(folds)``:
    a fold list built inside a loop can be garbage-collected and its address
    reused by the next one, which would make an identity key silently wrong.)

    With ``return_components`` the per-test-cell squared error and squared
    deviation are also returned, which is what the tile block bootstrap resamples.
    """
    Z = np.asarray(Z, dtype=np.float64)
    F = np.asarray(F, dtype=np.float64)
    if F.ndim == 1:
        F = F[:, None]
    num_parts, den_parts, cells = [], [], []

    if whiteners is not None:
        fp = _folds_fingerprint(folds)
        if whiteners.get("__fingerprint__") != fp:
            whiteners.clear()
            whiteners["__fingerprint__"] = fp

    for fi, (tr, te) in enumerate(folds):
        if tr.size < 10 or te.size < 2:
            continue
        cache_key = (fi, d_probe, var_keep)
        if whiteners is not None and cache_key in whiteners:
            transform = whiteners[cache_key]
        else:
            transform, _ = whiten_fit(Z[tr], d_probe=d_probe, var_keep=var_keep)
            if whiteners is not None:
                whiteners[cache_key] = transform
        Xtr, Xte = transform(Z[tr]), transform(Z[te])
        if Xtr.shape[1] == 0:
            continue
        reg = _make_regressor(kind, seed + 7919 * fi, Xtr.shape[0], mlp_kwargs=mlp_kwargs)
        pred = np.asarray(reg(Xtr, F[tr], Xte), dtype=np.float64)
        if pred.ndim == 1:
            pred = pred[:, None]
        mean_tr = F[tr].mean(0)
        num_parts.append(((F[te] - pred) ** 2).sum(1))
        den_parts.append(((F[te] - mean_tr) ** 2).sum(1))
        cells.append(te)

    if not num_parts:
        return (float("nan"), None) if return_components else float("nan")
    num = np.concatenate(num_parts)
    den = np.concatenate(den_parts)
    r2 = pooled_r2(float(num.sum()), float(den.sum()))
    if not return_components:
        return r2
    cells = np.concatenate(cells)
    comp = dict(num=num, den=den, cells=cells,
                tiles=None if tiles is None else np.asarray(tiles)[cells])
    return r2, comp


def permutation_floor(
    Z, F, folds, tiles, kind="mlp", d_probe=None, n_perm=50, seed=0,
    q=95.0, whiteners=None, mlp_kwargs=None,
):
    """Per-(latent, truth) floor: the identical probe on a TILE-PERMUTED truth.

    Returns the ``q``-th percentile over ``n_perm`` draws. The spec fixes
    ``n_perm=50``; lower it only knowingly, and note that fewer draws makes the
    95th percentile noisier in BOTH directions.
    """
    rng = np.random.default_rng(seed + 31337)
    vals = []
    for i in range(int(n_perm)):
        Fp = tile_permute(np.asarray(F), np.asarray(tiles), rng)
        vals.append(probe_r2(Z, Fp, folds, kind=kind, d_probe=d_probe,
                             seed=seed + 101 * i, whiteners=whiteners,
                             mlp_kwargs=mlp_kwargs))
    vals = np.asarray([v for v in vals if np.isfinite(v)], dtype=np.float64)
    if vals.size == 0:
        return float("nan"), np.array([])
    return float(np.percentile(vals, q)), vals


