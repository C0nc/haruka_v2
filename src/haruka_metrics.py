def block_bootstrap_ci(comp: dict, n_boot=2000, seed=0, alpha=0.05):
    """Block bootstrap of a pooled R^2, resampling whole TILES with replacement.

    ``comp`` is the ``return_components`` payload of :func:`probe_r2`. Resampling
    cells rather than tiles under spatial autocorrelation gives an interval that
    is far too tight and will manufacture significance.
    """
    if comp is None or comp.get("tiles") is None:
        return dict(point=float("nan"), lo=float("nan"), hi=float("nan"))
    rng = np.random.default_rng(seed)
    tiles = np.asarray(comp["tiles"])
    uniq, inv = np.unique(tiles, return_inverse=True)
    num_t = np.bincount(inv, weights=comp["num"], minlength=uniq.size)
    den_t = np.bincount(inv, weights=comp["den"], minlength=uniq.size)
    point = pooled_r2(num_t.sum(), den_t.sum())
    draws = np.empty(n_boot)
    for i in range(n_boot):
        s = rng.integers(0, uniq.size, uniq.size)
        draws[i] = pooled_r2(num_t[s].sum(), den_t[s].sum())
    lo, hi = np.percentile(draws[np.isfinite(draws)], [100 * alpha / 2, 100 * (1 - alpha / 2)])
    return dict(point=point, lo=float(lo), hi=float(hi), n_tiles=int(uniq.size))


def block_bootstrap_delta(comp_a: dict, comp_b: dict, n_boot=2000, seed=0, alpha=0.05):
    """PAIRED tile block bootstrap of ``R^2(a) - R^2(b)``.

    Both arms are recomputed on the SAME resampled tiles, which is what makes the
    interval a statement about the difference rather than about two noisy points.
    """
    rng = np.random.default_rng(seed)
    ta, tb = np.asarray(comp_a["tiles"]), np.asarray(comp_b["tiles"])
    uniq = np.union1d(np.unique(ta), np.unique(tb))
    ia = np.searchsorted(uniq, ta)
    ib = np.searchsorted(uniq, tb)
    na = np.bincount(ia, weights=comp_a["num"], minlength=uniq.size)
    da = np.bincount(ia, weights=comp_a["den"], minlength=uniq.size)
    nb = np.bincount(ib, weights=comp_b["num"], minlength=uniq.size)
    db = np.bincount(ib, weights=comp_b["den"], minlength=uniq.size)
    point = pooled_r2(na.sum(), da.sum()) - pooled_r2(nb.sum(), db.sum())
    draws = np.empty(n_boot)
    for i in range(n_boot):
        s = rng.integers(0, uniq.size, uniq.size)
        draws[i] = pooled_r2(na[s].sum(), da[s].sum()) - pooled_r2(nb[s].sum(), db[s].sum())
    d = draws[np.isfinite(draws)]
    lo, hi = np.percentile(d, [100 * alpha / 2, 100 * (1 - alpha / 2)])
    return dict(point=float(point), lo=float(lo), hi=float(hi),
                excludes_zero=bool(lo > 0 or hi < 0), n_tiles=int(uniq.size))


def paired_wilcoxon(a, b):
    """Paired Wilcoxon signed-rank over seeds. Returns statistic, p, median diff."""
    from scipy.stats import wilcoxon

    a, b = np.asarray(a, float), np.asarray(b, float)
    m = np.isfinite(a) & np.isfinite(b)
    if m.sum() < 2 or np.allclose(a[m], b[m]):
        return dict(stat=float("nan"), p=float("nan"),
                    median_diff=float(np.median(a[m] - b[m])) if m.any() else float("nan"))
    s, p = wilcoxon(a[m], b[m])
    return dict(stat=float(s), p=float(p), median_diff=float(np.median(a[m] - b[m])),
                n=int(m.sum()))


def heldout_nll_compare(nll_spatial, nll_ablation):
    """Per-cell held-out reconstruction NLL, spatial arm vs ablation.

    **If the spatial arm wins the latent metrics but not the NLL, the gain is
    regularisation or a lucky probe, not extracted information -- and the report
    must say so.** That verdict string is returned, not left to interpretation.
    """
    a = np.asarray(nll_spatial, float)
    b = np.asarray(nll_ablation, float)
    w = paired_wilcoxon(a, b)
    better = float(np.nanmean(a)) < float(np.nanmean(b))
    return dict(
        mean_spatial=float(np.nanmean(a)), mean_ablation=float(np.nanmean(b)),
        mean_diff=float(np.nanmean(a) - np.nanmean(b)), wilcoxon=w,
        spatial_wins=bool(better),
        verdict=("spatial arm improves held-out NLL" if better else
                 "spatial arm does NOT improve held-out NLL: any latent-metric gain "
                 "is regularisation or a lucky probe, not extracted information"),
    )


