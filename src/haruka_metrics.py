def whiten_fit(Z_train: np.ndarray, d_probe: int | None = None,
               var_keep: float = _VAR_KEEP, eig_floor: float = _EIG_FLOOR):
    """Fit a PCA-whitener on the TRAIN fold; returns a transform callable.

    Order matters. PCA FIRST (drop numerically degenerate directions, optionally
    truncate), THEN scale each retained component to unit variance. Whitening
    before truncating would make every component unit-variance and the truncation
    would then pick an arbitrary subspace.

    Fitting on the train fold only is both leakage-safe and exactly
    linear-invariant for OLS: for any invertible ``A``, ``Z`` and ``ZA`` produce
    whiteners spanning the same train row space, and least squares onto a span
    does not depend on its basis.

    **On the default ``var_keep = 1.0``.** The spec's recipe says "components
    covering 99% of variance", and justifies the whole probe by exact invariance
    to any invertible linear map. Those two requirements are in conflict, and the
    conflict is not cosmetic: "99% of the variance" is not a linear-invariant
    notion, so ``Z`` and ``Z @ A`` retain DIFFERENT subspaces and the probe stops
    being exactly invariant. Measured on a 10-d latent, a 99% cut left a residual
    of 1.4e-3 in R^2 between ``Z`` and ``Z @ A``; keeping the full numerical rank
    brings it to ~1e-15. The stated purpose wins over the stated recipe, so the
    default retains every component above the ``eig_floor`` numerical-rank
    threshold (which IS invariant, being a statement about degeneracy). Pass
    ``var_keep=0.99`` for the literal recipe, knowing it forfeits exactness.

    ``d_probe`` truncation forfeits exactness for the same reason, necessarily --
    it deliberately changes the subspace to match widths across latents. The spec
    is consistent here: it claims exactness only for the FULL-WIDTH variant. The
    width-matched headline numbers remain invariant to orthogonal transforms and
    to isotropic scaling, which is what makes them comparable across latents.
    """
    Z = np.asarray(Z_train, dtype=np.float64)
    mu = Z.mean(0)
    Zc = Z - mu
    n = max(Zc.shape[0] - 1, 1)
    _, s, Vt = np.linalg.svd(Zc, full_matrices=False)
    ev = (s ** 2) / n
    if ev.size == 0 or ev.max() <= 0:
        return lambda X: np.zeros((np.asarray(X).shape[0], 1)), 0
    keep = ev >= eig_floor * ev.max()
    ev, Vt = ev[keep], Vt[keep]
    if var_keep >= 1.0:
        k = ev.size
    else:
        cum = np.cumsum(ev) / ev.sum()
        k = min(int(np.searchsorted(cum, var_keep) + 1), ev.size)
    if d_probe is not None:
        k = min(k, int(d_probe))
    V = Vt[:k].T
    scale = 1.0 / np.sqrt(np.maximum(ev[:k], 1e-12))

    def transform(X):
        return ((np.asarray(X, dtype=np.float64) - mu) @ V) * scale

    return transform, k


